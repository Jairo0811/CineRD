const normalizar = value => String(value ?? "").normalize("NFD")
  .replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();

export function getSinopsisFaseE2Final(pelicula) {
  if (!pelicula) return null;
  const item = SINOPSIS_EDITORIALES_FASE_E2_FINAL[Number(pelicula.Id)];
  if (!item || normalizar(item.tituloReferencia) !== normalizar(pelicula.Titulo)) return null;
  if (Number(String(pelicula.FechaEstreno ?? "").slice(0, 4)) !== item.anioReferencia) return null;
  return item;
}
