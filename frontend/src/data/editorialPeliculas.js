const normalizar = (value) => String(value ?? "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();

export function getEditorialPelicula(pelicula) {
  const item = EDITORIALES_PELICULAS[Number(pelicula?.Id)];
  if (!item || !pelicula) return null;
  if (normalizar(pelicula.Titulo) !== normalizar(item.tituloReferencia)) return null;
  if (Number(String(pelicula.FechaEstreno || "").slice(0, 4)) !== item.anioReferencia) return null;
  return item;
}

export const editorialesDestacados = Object.entries(EDITORIALES_PELICULAS)
  .sort((a, b) => a[1].anioReferencia - b[1].anioReferencia)
  .map(([id, editorial]) => ({ id: Number(id), ...editorial }));
